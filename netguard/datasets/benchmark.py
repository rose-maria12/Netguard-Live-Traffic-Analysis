def map_cicflowmeter_row(row: Dict[str, Any]) -> Dict[str, Any]:
    """
    Map a raw CICFlowMeter CSV row into NetGuard's flow record representation.
    Explicitly handles striping of column whitespace common in CIC-IDS2017 CSV files.
    """
    clean = {k.strip(): str(v).strip() for k, v in row.items()}

    # Flow key fields
    proto_str = clean.get("Protocol", "6")
    try:
        proto_num = int(proto_str)
        proto = "TCP" if proto_num == 6 else ("UDP" if proto_num == 17 else "OTHER")
    except ValueError:
        proto = clean.get("Protocol", "TCP").upper()

    dst_port = 0
    for pk in ["Destination Port", "Dst Port", "dst_port"]:
        if pk in clean and clean[pk]:
            try:
                dst_port = int(clean[pk])
                break
            except ValueError:
                pass

    src_port = 0
    for pk in ["Source Port", "Src Port", "src_port"]:
        if pk in clean and clean[pk]:
            try:
                src_port = int(clean[pk])
                break
            except ValueError:
                pass

    src_ip = clean.get("Source IP", clean.get("Src IP", clean.get("src_ip", "192.168.10.50")))
    dst_ip = clean.get("Destination IP", clean.get("Dst IP", clean.get("dst_ip", "192.168.10.1")))

    # Packets and bytes
    try:
        fwd_pkts = int(clean.get("Total Fwd Packets", clean.get("Tot Fwd Pkts", 1)))
    except ValueError:
        fwd_pkts = 1

    try:
        bwd_pkts = int(clean.get("Total Backward Packets", clean.get("Tot Bwd Pkts", 0)))
    except ValueError:
        bwd_pkts = 0

    try:
        bytes_fwd = int(clean.get("Total Length of Fwd Packets", clean.get("TotLen Fwd Pkts", 0)))
    except ValueError:
        bytes_fwd = 0

    try:
        bytes_bwd = int(clean.get("Total Length of Bwd Packets", clean.get("TotLen Bwd Pkts", 0)))
    except ValueError:
        bytes_bwd = 0

    # Duration in microseconds -> seconds
    try:
        duration_us = float(clean.get("Flow Duration", clean.get("flow_duration", 0)))
        duration_s = max(0.001, duration_us / 1_000_000.0)
    except ValueError:
        duration_s = 0.1

    # TCP flags
    syn_count = int(clean.get("SYN Flag Count", 0)) if str(clean.get("SYN Flag Count", "")).isdigit() else 0
    rst_count = int(clean.get("RST Flag Count", 0)) if str(clean.get("RST Flag Count", "")).isdigit() else 0

    flags_fwd = set()
    if syn_count > 0:
        flags_fwd.add("S")
    flags_bwd = set()
    if rst_count > 0:
        flags_bwd.add("R")

    # Ground truth label
    raw_label = clean.get("Label", clean.get("label", "BENIGN")).strip()
    is_malicious = raw_label.upper() not in {"BENIGN", "NORMAL", "0"}

    # Derive state
    if rst_count > 0 or (fwd_pkts > 0 and bwd_pkts == 0):
        state = "reset" if rst_count > 0 else "no_response"
    else:
        state = "established"

    base_ts = 1000.0  # Synthetic epoch for deterministic grouping

    return {
        # Offline DB schema format
        "initiator_ip": src_ip,
        "responder_ip": dst_ip,
        "initiator_port": src_port,
        "responder_port": dst_port,
        "proto": proto,
        "start_ts": base_ts,
        "end_ts": base_ts + duration_s,
        "duration": duration_s,
        "pkts_fwd": fwd_pkts,
        "pkts_rev": bwd_pkts,
        "packets_fwd": fwd_pkts,
        "packets_bwd": bwd_pkts,
        "bytes_fwd": bytes_fwd,
        "bytes_rev": bytes_bwd,
        "syn_count": syn_count,
        "rst_count": rst_count,
        "state": state,
        "first_frame": 1,
        "last_frame": 2,
        # Live schema aliases
        "ip_src": src_ip,
        "ip_dst": dst_ip,
        "sport": src_port,
        "dport": dst_port,
        "tcp_flags_fwd": ",".join(flags_fwd),
        "tcp_flags_bwd": ",".join(flags_bwd),
        "packets_total": fwd_pkts + bwd_pkts,
        "bytes_total": bytes_fwd + bytes_bwd,
        "label": raw_label,
        "is_malicious": is_malicious,
    }


def evaluate_csv_dataset(
    csv_path: Union[str, Path],
    dataset_name: str = "CIC-IDS2017",
    max_rows: Optional[int] = None,
    config: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """
    Evaluate NetGuard rule detectors against authentic flow CSV records.
    Computes confusion matrix, precision, recall, F1, FPR, accuracy, and throughput.
    """
    csv_file = Path(csv_path)
    if not csv_file.exists():
        raise FileNotFoundError(f"Benchmark CSV file not found: {csv_path}")

    cfg = config or load_config()
    start_bench = time.perf_counter()

    flows: List[Dict[str, Any]] = []
    ground_truth: List[bool] = []
    labels: List[str] = []

    with open(csv_file, mode="r", encoding="utf-8-sig", errors="replace") as f:
        reader = csv.DictReader(f)
        for i, row in enumerate(reader):
            if max_rows and i >= max_rows:
                break
            mapped = map_cicflowmeter_row(row)
            flows.append(mapped)
            ground_truth.append(mapped["is_malicious"])
            labels.append(mapped["label"])

    total_flows = len(flows)
    if total_flows == 0:
        return {"error": "CSV file contained no parseable rows."}

    # Run Port Scan & Brute Force rule detectors across flow subsets
    detected_indices: set[int] = set()

    # Port scan check
    port_scan_findings = detect_port_scan(flows, config=cfg)
    for f in port_scan_findings:
        src = f.src_ip
        dst = f.dst_ip
        for idx, fl in enumerate(flows):
            if fl["ip_src"] == src and (not dst or fl["ip_dst"] == dst):
                detected_indices.add(idx)

    # Brute force check
    bf_findings = detect_brute_force(flows, config=cfg)
    for f in bf_findings:
        src = f.src_ip
        dst = f.dst_ip
        dport = getattr(f, "dst_port", None)
        for idx, fl in enumerate(flows):
            if fl["ip_src"] == src and (not dst or fl["ip_dst"] == dst) and (not dport or fl["dport"] == dport):
                detected_indices.add(idx)

    elapsed = time.perf_counter() - start_bench
    throughput_fps = round(total_flows / elapsed, 1) if elapsed > 0 else 0.0

    # Calculate confusion matrix
    tp = sum(1 for i in range(total_flows) if ground_truth[i] and i in detected_indices)
    fp = sum(1 for i in range(total_flows) if (not ground_truth[i]) and i in detected_indices)
    fn = sum(1 for i in range(total_flows) if ground_truth[i] and i not in detected_indices)
    tn = sum(1 for i in range(total_flows) if (not ground_truth[i]) and i not in detected_indices)

    precision = round(tp / (tp + fp), 4) if (tp + fp) > 0 else 0.0
    recall = round(tp / (tp + fn), 4) if (tp + fn) > 0 else 0.0
    f1 = round(2 * precision * recall / (precision + recall), 4) if (precision + recall) > 0 else 0.0
    fpr = round(fp / (fp + tn), 4) if (fp + tn) > 0 else 0.0
    accuracy = round((tp + tn) / total_flows, 4) if total_flows > 0 else 0.0

    # Breakdown by attack class
    attack_breakdown: Dict[str, Dict[str, int]] = {}
    for idx, lbl in enumerate(labels):
        if lbl not in attack_breakdown:
            attack_breakdown[lbl] = {"total": 0, "detected": 0}
        attack_breakdown[lbl]["total"] += 1
        if idx in detected_indices:
            attack_breakdown[lbl]["detected"] += 1

    return {
        "dataset_name": dataset_name,
        "csv_path": str(csv_file),
        "total_flows": total_flows,
        "elapsed_seconds": round(elapsed, 3),
        "throughput_fps": throughput_fps,
        "confusion_matrix": {
            "TN": tn,
            "FP": fp,
            "FN": fn,
            "TP": tp,
            "matrix": [[tn, fp], [fn, tp]],
        },
        "metrics": {
            "precision": precision,
            "recall": recall,
            "f1_score": f1,
            "false_positive_rate": fpr,
            "accuracy": accuracy,
        },
        "findings_count": len(port_scan_findings) + len(bf_findings),
        "attack_breakdown": attack_breakdown,
        "metadata": asdict(DATASET_REGISTRY.get(dataset_name, DATASET_REGISTRY["CIC-IDS2017"])),
    }


def evaluate_pcap_dataset(
    pcap_path: Union[str, Path],
    expected_alerts: List[Dict[str, Any]],
    db_path: Any = None,
    config: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """
    Run authentic PCAP through the full NetGuard forensic ingestion,
    flow building, and detection pipeline, comparing against expected alerts.
    """
    pcap_file = Path(pcap_path)
    if not pcap_file.exists():
        raise FileNotFoundError(f"PCAP file not found: {pcap_path}")

    cfg = config or load_config()
    start_bench = time.perf_counter()

    cap = import_capture(pcap_file, db_path=db_path, config=cfg)
    res = run_analysis(cap["id"], db_path=db_path, config=cfg)

    elapsed = time.perf_counter() - start_bench
    frames = cap.get("frames_total", 0)
    throughput_pps = round(frames / elapsed, 1) if elapsed > 0 else 0.0

    # Collect observed rule alerts
    observed_alerts = []
    for inc in res.get("incidents", []):
        for a in inc.alerts:
            observed_alerts.append({
                "alert_type": a.alert_type,
                "src_ip": a.src_ip,
                "dst_ip": a.dst_ip,
                "rule_name": a.rule_name,
                "severity": a.severity,
            })

    # Evaluate matches against ground truth
    matched_expected = set()
    tp = 0
    fp = 0
    for obs in observed_alerts:
        match_found = False
        for idx, exp in enumerate(expected_alerts):
            if (
                obs["alert_type"] == exp.get("alert_type")
                and obs["src_ip"] == exp.get("src_ip")
                and (not exp.get("dst_ip") or obs["dst_ip"] == exp.get("dst_ip"))
            ):
                match_found = True
                matched_expected.add(idx)
                break
        if match_found:
            tp += 1
        else:
            fp += 1

    fn = len(expected_alerts) - len(matched_expected)
    precision = round(tp / (tp + fp), 4) if (tp + fp) > 0 else 0.0
    recall = round(tp / (tp + fn), 4) if (tp + fn) > 0 else 0.0
    f1 = round(2 * precision * recall / (precision + recall), 4) if (precision + recall) > 0 else 0.0

    return {
        "pcap_path": str(pcap_file),
        "frames_total": frames,
        "elapsed_seconds": round(elapsed, 3),
        "throughput_pps": throughput_pps,
        "alerts_count": len(observed_alerts),
        "incidents_count": res.get("incidents_count", 0),
        "evaluation": {
            "TP": tp,
            "FP": fp,
            "FN": fn,
            "precision": precision,
            "recall": recall,
            "f1_score": f1,
        },
        "observed_alerts": observed_alerts,
    }
